	private static void generateTest()
	{
		Random r = new Random();
		int x = r.nextInt(95) + 5;

		int[] ints = new int[x];

		for (int i = 0; i < x; i++)
		{
			ints[i] = r.nextInt(20 + 1);
		}

		String input = Arrays.toString(ints).replaceAll("\\[", "{").replaceAll("]", "}").replaceAll(" ", "");
		String output = String.valueOf(validate(ints));
		System.out.printf("MAP.put(new int[]%s,%s);%n", input, output);
	}

	public static int validate(int[] H)
	{
		int ans = 0;
		int i = 0;
		int j = H.length - 1;
		int res = 0;

		while (i < j)
		{
			if (H[i] <= H[j])
			{
				res = H[i] * (j - i);
				i++;
			}
			else
			{
				res = H[j] * (j - i);
				j--;
			}
			if (res > ans)
			{
				ans = res;
			}
		}
		return ans;
	}
