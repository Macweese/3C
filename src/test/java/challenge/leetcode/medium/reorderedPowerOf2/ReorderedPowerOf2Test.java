	// Leetcode solution
	// Explanation
	// This works by placing the value of a digit n at the n-th position,
	// continuing through the number and adding to itself, similar to bits
	// e.g. 1024
	// becomes a number: 0 000 000 000
	// 1 -> 0 000 000 000 + 10^1 = 0 000 000 010
	// 0 -> 0 000 000 010 + 10^0 = 0 000 000 011
	// 2 -> 0 000 000 011 + 10^2 = 0 000 000 111
	// 4 -> 0 000 000 211 + 10^4 = 0 000 010 111
	//
	// if there are duplicates, then they are simply added:
	// 4 -> 0 000 010 111 + 10^4 = 0 000 020 111
	// And the inverse can be done to retrieve the individual digits
	// But in this case, there's no need to do so,
	// instead, the number is checked against the products from numbers of power of 2;
	// 2^0, 2^1, 2^2, 2^3, 2^4, 2^5, ... 2^n < 10^9
	// Clever solution
	//
	// NOTE:
	// But this will not work for numbers greater than 10^9, because if a digit occurs more than 9 times,
	// it is carried over, and the count is muddied
	// e.g. 1 111 111 111
	// would become
	// 1 -> 0 000 000 000 + 10^1 = 0 000 000 010
	// 1 -> 0 000 000 010 + 10^1 = 0 000 000 020
	// 1 -> 0 000 000 020 + 10^1 = 0 000 000 030
	// 1 -> 0 000 000 030 + 10^1 = 0 000 000 040
	// 1 -> 0 000 000 040 + 10^1 = 0 000 000 050
	// 1 -> 0 000 000 050 + 10^1 = 0 000 000 060
	// 1 -> 0 000 000 060 + 10^1 = 0 000 000 070
	// 1 -> 0 000 000 070 + 10^1 = 0 000 000 080
	// 1 -> 0 000 000 080 + 10^1 = 0 000 000 090
	// 1 -> 0 000 000 090 + 10^1 = 0 000 000 100
	// This could therefore be misinterpreted as
	// 10 x 1s exist
	// or
	// 1 x 2s exist
	// The number is either
	// 1,111,111,111 or 2
	public static boolean reorderedPowerOf2(int N)
	{
		long c = counter(N);
		for (int i = 0; i < 32; i++)
		{
			if (counter(1 << i) == c)
			{
				return true;
			}
		}
		return false;
	}

	public static long counter(int N)
	{
		long res = 0;
		for (; N > 0; N /= 10)
		{
			res += (int) Math.pow(10, N % 10);
		}
		return res;
	}
